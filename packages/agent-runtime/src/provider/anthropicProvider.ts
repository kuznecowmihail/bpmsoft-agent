const STOP_ABORT_DELAY_MS = 5000;

export interface ToolPermissionRequest {
	toolName: string;
	input: Record<string, unknown>;
}

export interface RunBpmsoftAgentQueryOptions {
	/** Anthropic API key — never logged, never persisted by this function. */
	apiKey: string;
	prompt: string;
	cwd: string;
	model?: string;
	/** Reasoning effort for the model (see `listClaudeModels`); omit for the SDK default. */
	effort?: ClaudeEffort;
	/**
	 * Session id from a previous turn (see `sessionId` on `system_init` /
	 * `result` events). When set, the SDK loads that conversation's history,
	 * so follow-up answers (e.g. to the agent's clarifying questions) keep
	 * their context. Omit to start a new conversation.
	 */
	resume?: string;
	/**
	 * File-access sandbox. When set, every tool call is checked by a
	 * PreToolUse hook before it runs: reads only under `readRoots` (plus the
	 * knowledge directory, added automatically), writes only under
	 * `writeRoots`. Violations are denied without asking the user.
	 */
	sandbox?: { readRoots: string[]; writeRoots: string[] };
	/**
	 * Extra absolute directories the agent may read/write beyond `cwd` — e.g.
	 * BPMSoft's `Resources`/`Autogenerated`/`conf/content`
	 * siblings alongside the `Pkg` working directory, so the agent can
	 * research BPMSoft's own implementation, not just edit files under `Pkg`.
	 * The on-demand knowledge directory (see `systemPrompt.ts`) is always
	 * added on top of this list, regardless of what's passed here.
	 */
	additionalDirectories?: string[];
	/**
	 * Called before each tool execution that would otherwise prompt for
	 * permission (file writes, Bash, etc.) — resolve `true` to allow, `false`
	 * to deny. Omit to keep the SDK's own default (without a real callback,
	 * the SDK auto-denies any tool call requiring permission — see
	 * `@anthropic-ai/claude-agent-sdk`'s `CanUseTool` docs).
	 */
	requestToolPermission?: (request: ToolPermissionRequest) => Promise<boolean>;
	/** Stops the turn: interrupt first, then hard abort of the CLI after STOP_ABORT_DELAY_MS. */
	signal?: AbortSignal;
	/** Read-only CRM database tool (see createCrmDbTool); omit when the user has not enabled database access. */
	dbTool?: CrmDbTool;
	/** CRM stand actions (see createCrmTools); omit when the user has not enabled them. */
	crmTools?: CrmTool[];
	/** Tools of the host app (built-in CRM browser and others); omit when none. */
	appTools?: AppTool[];
}

/** Zod shape of an app tool's parameters (flat string, number or boolean values). */
function zodShape(appTool: AppTool): Record<string, z.ZodType> {
	const shape: Record<string, z.ZodType> = {};
	for (const [name, param] of Object.entries(appTool.params)) {
		let schema: z.ZodType = param.type === "number" ? z.number() : param.type === "boolean" ? z.boolean() : z.string();
		schema = schema.describe(param.description);
		shape[name] = param.optional ? schema.optional() : schema;
	}
	return shape;
}

/**
 * Folder where the Claude Agent SDK stores oversized tool outputs for sessions started in `cwd` (read-only for the agent).
 * The SDK saves large tool outputs to ~/.claude/projects/<normalized-cwd>/<session>/tool-results/<id>.txt
 * where normalized-cwd replaces every non-alphanumeric character with "-".
 */
export function sdkToolResultsDirectory(cwd: string): string {
	return path.join(os.homedir(), ".claude", "projects", path.resolve(cwd).replace(/[^a-zA-Z0-9]/g, "-"));
}

/** Tools whose background mode would outlive the turn: the query closes on the first result and kills them. */
const FOREGROUND_TOOLS = new Set(["Agent", "Task", "Bash"]);

/** Input with run_in_background: false for Agent/Task/Bash when it is not already false; undefined when nothing changes. */
export function foregroundToolInput(toolName: string, input: Record<string, unknown>): Record<string, unknown> | undefined {
	if (!FOREGROUND_TOOLS.has(toolName) || input.run_in_background === false) {
		return undefined;
	}
	// Agent/Task default to background, so any value except false is forced to foreground.
	// Bash is foreground by default: only an explicit true needs changing.
	if (toolName === "Bash" && input.run_in_background !== true) {
		return undefined;
	}
	return { ...input, run_in_background: false };
}

/** Claude Code switches that stop non-essential traffic to Anthropic and third parties: usage metrics, error reports, /feedback uploads, surveys. Requests to the model are not affected. */
export const NONESSENTIAL_TRAFFIC_OFF: Readonly<Record<string, string>> = {
	CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC: "1",
	DISABLE_TELEMETRY: "1",
	DISABLE_ERROR_REPORTING: "1",
	DISABLE_FEEDBACK_COMMAND: "1"
};

/** Environment of the Claude Code process: the app's environment, the API key, and non-essential traffic switched off (our values win). */
export function agentEnv(apiKey: string | undefined, baseEnv: NodeJS.ProcessEnv = process.env): Record<string, string | undefined> {
	return { ...baseEnv, ANTHROPIC_API_KEY: apiKey, ...NONESSENTIAL_TRAFFIC_OFF };
}

/**
 * Builds a single-turn streaming prompt: yields exactly one user message,
 * then stays open (awaiting `close()`) instead of returning immediately.
 *
 * This is required for `canUseTool` to work at all. The SDK's one-shot
 * string-`prompt` form closes stdin right after sending it (confirmed by
 * reading the SDK's own `sdk.d.ts`: "the string `prompt` form and `-p`,
 * which close stdin") — and since `canUseTool`'s permission control-response
 * travels back to the CLI subprocess over that same stdin channel, a closed
 * stdin means the user's answer can never be delivered ("Stream closed",
 * observed on every write-requiring tool call in manual testing). Streaming
 * input mode keeps stdin open until we explicitly `close()` it, which
 * `runBpmsoftAgentQuery` does right after the turn's `result` message.
 */
function createSingleTurnPromptStream(promptText: string): {
	stream: AsyncIterable<SDKUserMessage>;
	close: () => void;
} {
	let resolveClose: () => void = () => {};
	const closeSignal = new Promise<void>((resolve) => {
		resolveClose = resolve;
	});
	async function* generate(): AsyncGenerator<SDKUserMessage> {
		yield {
			type: "user",
			message: { role: "user", content: promptText },
			parent_tool_use_id: null
		};
		await closeSignal;
	}
	return { stream: generate(), close: () => resolveClose() };
}

/**
 * Thin wrapper around the real Claude Agent SDK's `query()`. NOT unit-tested
 * directly (it spawns a real CLI subprocess and requires a real
 * `ANTHROPIC_API_KEY`); the message
 * mapping it delegates to (`mapSdkMessage`) is unit-tested with hand-built
 * fake messages instead. A manual smoke-test script exercising this function
 * end-to-end is a separate follow-up once a real API key is available.
 */
export async function* runBpmsoftAgentQuery(
	options: RunBpmsoftAgentQueryOptions
): AsyncGenerator<AgentEvent, void> {
	// The on-demand knowledge directory (packages/agent-runtime/knowledge/) is
	// always accessible, regardless of which BPMSoft project is open — see
	// systemPrompt.ts for why this exists (avoids bloating every turn's
	// context with topic-specific findings that most tasks don't need).
	const knowledgeDir = path.join(__dirname, "../../knowledge");
	const additionalDirectories = [...(options.additionalDirectories ?? []), knowledgeDir];

	const toolResultsDir = sdkToolResultsDirectory(options.cwd);
	const sandboxPolicy = options.sandbox
		? { readRoots: [...options.sandbox.readRoots, knowledgeDir, toolResultsDir], writeRoots: options.sandbox.writeRoots, sourceRoots: [knowledgeDir, toolResultsDir] }
		: undefined;
	const osShellSandbox = hasOsShellSandbox();
	const shellApproval: ShellApprovalOptions = { osSandbox: osShellSandbox, cwd: options.cwd, trustedScriptDirs: [path.join(knowledgeDir, "scripts")] };
	// Folders the agent wrote to in this turn; the SDK's staging folders there are removed after the turn.
	const touchedDirs = new Set<string>([options.cwd]);
	const abortController = new AbortController();

	const servers: NonNullable<Options["mcpServers"]> = {};
	if (options.dbTool) {
		servers.crm_db = createSdkMcpServer({
			name: "crm_db",
			version: "1.0.0",
			tools: [
				tool(
					options.dbTool.name,
					options.dbTool.description,
					{ sql: z.string().describe("Один запрос SELECT или WITH") },
					async (args) => {
						const result = await options.dbTool!.execute(args.sql);
						return { content: [{ type: "text", text: result.text }], isError: result.isError };
					},
					{ annotations: { readOnlyHint: true }, alwaysLoad: true }
				)
			]
		});
	}
	if (options.crmTools?.length) {
		servers.crm = createSdkMcpServer({
			name: "crm",
			version: "1.0.0",
			tools: options.crmTools.map((crmTool) =>
				tool(
					crmTool.name,
					crmTool.description,
					{},
					async () => {
						const result = await crmTool.execute();
						return { content: [{ type: "text", text: result.text }], isError: result.isError };
					},
					{ alwaysLoad: true }
				)
			)
		});
	}
	if (options.appTools?.length) {
		servers.app = createSdkMcpServer({
			name: "app",
			version: "1.0.0",
			tools: options.appTools.map((appTool) =>
				tool(
					appTool.name,
					appTool.description,
					zodShape(appTool),
					async (args) => {
						const result = await appTool.execute(args as Record<string, unknown>);
						return { content: appToolContent(result), isError: result.isError };
					},
					{ alwaysLoad: true }
				)
			)
		});
	}

	const sdkOptions: Options = {
		cwd: options.cwd,
		model: options.model,
		effort: options.effort,
		resume: options.resume,
		abortController,
		env: agentEnv(options.apiKey),
		systemPrompt: { type: "custom", prompt: buildBpmsoftSystemPrompt(knowledgeDir, { dbQuery: Boolean(options.dbTool), crmActions: Boolean(options.crmTools?.length), crmBrowser: Boolean(options.appTools?.some((t) => t.name.startsWith("crm_browser_"))), crmRequest: Boolean(options.appTools?.some((t) => t.name === "crm_request")) }) },
		// Isolation from the developer's own Claude Code setup: without these the
		// SDK loads ~/.claude settings (plugins, SessionStart hooks) and personal
		// skills into the BPMSoft agent. Our behaviour comes only from the system
		// prompt, the knowledge directory and the sandbox hook below.
		settingSources: [],
		skills: [],
		additionalDirectories,
		// Bash in the OS sandbox: no writes outside Pkg, no reads in the home folder outside the project and knowledge, no network, no API keys in the environment.
		sandbox: options.sandbox && osShellSandbox && sandboxPolicy ? buildShellSandbox({ writeRoots: options.sandbox.writeRoots, readRoots: sandboxPolicy.readRoots, homeDir: os.homedir() }) : undefined,
		mcpServers: Object.keys(servers).length > 0 ? servers : undefined,
		hooks: sandboxPolicy
			? {
					PreToolUse: [
						{
							hooks: [
								async (input) => {
									if (input.hook_event_name !== "PreToolUse") {
										return {};
									}
									const toolInput = (input.tool_input ?? {}) as Record<string, unknown>;
									for (const key of ["file_path", "notebook_path", "path"]) {
										const value = toolInput[key];
										if (typeof value === "string" && value !== "") {
											touchedDirs.add(path.dirname(path.resolve(input.cwd || options.cwd, value)));
										}
									}
									const decision = checkToolAccess(
										input.tool_name,
										toolInput,
										input.cwd || options.cwd,
										sandboxPolicy
									);
									if (!decision.allowed) {
										return {
											hookSpecificOutput: {
												hookEventName: "PreToolUse",
												permissionDecision: "deny",
												permissionDecisionReason: decision.reason
											}
										};
									}
									const updatedInput = foregroundToolInput(input.tool_name, toolInput);
									// Auto-approve tool calls that don't require permission prompts
									if (options.requestToolPermission && isAutoApprovedToolCall(input.tool_name, toolInput, shellApproval)) {
										return {
											hookSpecificOutput: {
												hookEventName: "PreToolUse",
												permissionDecision: "allow",
												permissionDecisionReason: "Разрешено политикой приложения: чтение проекта или запись в Pkg без удаления",
												...(updatedInput ? { updatedInput } : {})
											}
										};
									}
									return updatedInput ? { hookSpecificOutput: { hookEventName: "PreToolUse", updatedInput } } : {};
								}
							]
						}
					]
				}
			: undefined,
		canUseTool: options.requestToolPermission
			? async (toolName, input) => {
					const toolInput = input as Record<string, unknown>;
					if (isReadOnlyToolCall(toolName, toolInput, shellApproval)) {
						return { behavior: "allow" };
					}
					// File changes inside Pkg run without a prompt: the sandbox hook has already
					// denied anything outside it; re-checked here as a second line of defence.
					// Deletions, git state changes and risky programs still ask the user.
					if (
						sandboxPolicy &&
						isAutoApprovedToolCall(toolName, toolInput, shellApproval) &&
						checkToolAccess(toolName, toolInput, options.cwd, sandboxPolicy).allowed
					) {
						return { behavior: "allow" };
					}
					const approved = await options.requestToolPermission!({ toolName, input: toolInput });
					return approved
						? { behavior: "allow" }
						: { behavior: "deny", message: "Пользователь отклонил выполнение инструмента" };
				}
			: undefined
	};

	const { stream, close } = createSingleTurnPromptStream(options.prompt);
	const startedAt = Date.now();
	let sessionId: string | undefined = options.resume;
	let abortTimer: NodeJS.Timeout | undefined;
	const q = query({ prompt: stream, options: sdkOptions });
	const onStop = () => {
		q.interrupt().catch(() => undefined);
		abortTimer = setTimeout(() => abortController.abort(), STOP_ABORT_DELAY_MS);
	};
	const signal = options.signal;
	if (signal?.aborted) {
		onStop();
	} else {
		signal?.addEventListener("abort", onStop, { once: true });
	}
	let resultSent = false;
	try {
		try {
			for await (const message of q) {
				const event = mapSdkMessage(message);
				if (event.type === "system_init" && event.sessionId) {
					sessionId = event.sessionId;
				}
				if (event.type === "result") {
					resultSent = true;
					yield signal?.aborted ? { ...event, success: false, stopped: true } : event;
					break;
				}
				yield event;
			}
		} catch (error) {
			if (!signal?.aborted) {
				throw error;
			}
		}
		if (signal?.aborted && !resultSent) {
			yield { type: "result", success: false, stopped: true, durationMs: Date.now() - startedAt, sessionId };
		}
	} finally {
		signal?.removeEventListener("abort", onStop);
		if (abortTimer) {
			clearTimeout(abortTimer);
		}
		close();
		try {
			cleanupStagingDirs(touchedDirs, options.sandbox?.writeRoots ?? []);
		} catch {
			// Best-effort cleanup: a failure must not break the turn.
		}
	}
}
