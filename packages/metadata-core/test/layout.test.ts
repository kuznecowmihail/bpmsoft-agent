import { describe, it, expect, beforeAll, afterAll } from "vitest";
import * as fs from "fs";
import * as path from "path";
import * as os from "os";
import { resolveAppLayout } from "../src/layout/workspaceLayout";

describe("resolveAppLayout", () => {
	let tmpRoot: string;

	beforeAll(() => {
		tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "bpmsoft-layout-"));
		const configurationRoot = path.join(tmpRoot, "BPMSoft.Configuration");
		const pkgRoot = path.join(configurationRoot, "Pkg");
		const packageDir = path.join(pkgRoot, "MyPackage");
		fs.mkdirSync(path.join(packageDir, "Schemas"), { recursive: true });
		fs.mkdirSync(path.join(configurationRoot, "Autogenerated"), { recursive: true });
	});

	afterAll(() => {
		fs.rmSync(tmpRoot, { recursive: true, force: true });
	});

	it("resolves 'pkg' kind when opening .../BPMSoft.Configuration/Pkg", () => {
		const pkgRoot = path.join(tmpRoot, "BPMSoft.Configuration", "Pkg");
		const layout = resolveAppLayout(pkgRoot);
		expect(layout.kind).toBe("pkg");
		expect(layout.pkgRoot).toBe(pkgRoot);
		expect(layout.configurationRoot).toBe(path.join(tmpRoot, "BPMSoft.Configuration"));
	});

	it("resolves 'configuration' kind when opening .../BPMSoft.Configuration", () => {
		const configurationRoot = path.join(tmpRoot, "BPMSoft.Configuration");
		const layout = resolveAppLayout(configurationRoot);
		expect(layout.kind).toBe("configuration");
		expect(layout.autogeneratedRoot).toBe(path.join(configurationRoot, "Autogenerated"));
	});

	it("returns 'unknown' for an unrelated folder", () => {
		const other = fs.mkdtempSync(path.join(os.tmpdir(), "not-bpmsoft-"));
		try {
			const layout = resolveAppLayout(other);
			expect(layout.kind).toBe("unknown");
		} finally {
			fs.rmSync(other, { recursive: true, force: true });
		}
	});
});
