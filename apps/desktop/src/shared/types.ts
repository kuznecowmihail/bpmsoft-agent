import type { AgentEvent } from '@bpmsoft-agent/agent-runtime'

export type BpmsoftLayoutKind = 'app-root' | 'configuration' | 'pkg' | 'package' | 'unknown'

/** Result of the file design mode check of the stand: whether it reads its files from the file system. */
export interface FileDesignModeCheck {
	status: 'ok' | 'disabled' | 'notFound'
	configPath?: string
	problems: string[]
}

export interface ProjectValidationResult {
	isValid: boolean
	path: string
	kind: BpmsoftLayoutKind
	pkgRoot?: string
	appRoot?: string
	resourcesRoot?: string
	autogeneratedRoot?: string
	confContent?: string
	reason?: string
	/** Set when the folder is a BPMSoft project but the file design mode check failed. */
	fileDesignMode?: FileDesignModeCheck
	/** True when the project was refused because the computer misses a blocking requirement. */
	environmentBlocked?: boolean
}

/** A project opened earlier, shown on the start screen. */
export interface RecentProject {
	path: string
	/** Folder name. */
	name: string
	/** Parent folder, home directory shown as ~. */
	location: string
}

export type AgentProvider = 'claude' | 'cursor'

export type ClaudeEffort = 'low' | 'medium' | 'high' | 'xhigh' | 'max'

export interface CursorModelParam {
	id: string
	value: string
}

/** Model picker entry: a Cursor model or one of its variants (thinking, reasoning effort, Max). */
export interface CursorModelOption {
	id: string
	name: string
	params?: CursorModelParam[]
	recommended: boolean
}

/** Claude model picker entry: a model in its default effort or one of its effort variants. */
export interface ClaudeModelOption {
	id: string
	name: string
	effort?: ClaudeEffort
	recommended: boolean
}

export interface AgentSettings {
	provider: AgentProvider
	/** Cursor model id used when provider is 'cursor'. */
	cursorModel: string
	cursorModelParams: CursorModelParam[]
	cursorModelName: string
	/** Claude model id; '' = SDK default. */
	claudeModel: string
	claudeEffort: ClaudeEffort | ''
	claudeModelName: string
	hasClaudeKey: boolean
	hasCursorKey: boolean
	/**
	 * Read-only CRM database access; empty host/port/user = values from ConnectionStrings.config.
	 * Host, port, user, password and the CRM address, user, password belong to the opened project.
	 */
	dbAccessEnabled: boolean
	dbConfirmQueries: boolean
	dbHost: string
	dbPort: string
	dbUser: string
	hasDbPassword: boolean
	/**
	 * Agent may run «Обновить из файловой системы» and compile+restart on the stand;
	 * the user must have the «Системный администратор» role.
	 */
	crmActionsEnabled: boolean
	crmConfirmActions: boolean
	/** Built-in CRM browser: the agent reads CRM pages in a side panel of the main window; clicks need the user's approval. */
	crmBrowserEnabled: boolean
	crmUrl: string
	crmUser: string
	hasCrmPassword: boolean
	/** Jira и Confluence — общие для всех проектов; токены в Keychain/DPAPI. */
	jiraUrl: string
	jiraEmail: string
	jiraAcceptanceField: string
	confluenceUrl: string
	confluenceEmail: string
	hasJiraToken: boolean
	hasConfluenceToken: boolean
}

/** State of the CRM page shown in the browser panel of the main window. */
export interface CrmBrowserState {
	url: string
	title: string
	loading: boolean
	hasPage: boolean
}

export interface DbSettingsPatch {
	dbAccessEnabled?: boolean
	dbConfirmQueries?: boolean
	dbHost?: string
	dbPort?: string
	dbUser?: string
}

export interface CrmSettingsPatch {
	crmActionsEnabled?: boolean
	crmConfirmActions?: boolean
	crmBrowserEnabled?: boolean
	crmUrl?: string
	crmUser?: string
}

/** Global Jira and Confluence settings; tokens are set separately. */
export interface TrackerSettingsPatch {
	jiraUrl?: string
	jiraEmail?: string
	jiraAcceptanceField?: string
	confluenceUrl?: string
	confluenceEmail?: string
}

/** One entry of the chat replay: a user message or an agent event, in log order. */
export type ChatReplayItem =
	| { kind: 'user'; ts: string; text: string }
	| { kind: 'agent'; ts: string; event: AgentEvent }

/** Model used by a chat turn, as recorded in the chat log. */
export interface ChatModelRef {
	id: string | null
	effort?: string | null
	params?: CursorModelParam[]
}

/** Result of reading a chat .jsonl log for replay and metadata. */
export interface ParsedChatLog {
	projectPath: string | null
	readRoot: string | null
	startedAt: string | null
	title: string
	provider: AgentProvider | null
	model: ChatModelRef | null
	sessionId: string | null
	lastTurnInterrupted: boolean
	lastTurnStopped: boolean
	updatedAt: string | null
	items: ChatReplayItem[]
}

/** Строка списка чатов текущего стенда. */
export interface ChatSummary {
	id: string
	title: string
	provider: AgentProvider
	updatedAt: string
	contextLost: boolean
}

/** Чат, открытый из истории: лента для показа и причина, почему его нельзя продолжить. */
export interface OpenedChat {
	id: string
	items: ChatReplayItem[]
	readOnlyReason: string | null
	note: string | null
}

/** Device and tool versions of the computer the app runs on, shown in the environment check. */
export interface DeviceInfo {
  platform: string
  arch: string
  rosetta: boolean
  osVersion: string
  osRelease: string
  cpuModel: string
  memoryGb: number
  appVersion: string
  electronVersion: string
  nodeVersion: string | null
  gitVersion: string | null
  gitBashPath: string | null
}

export type EnvCheckId = 'os' | 'node' | 'git' | 'gitBash'

/** One line of the environment check. */
export interface EnvCheck {
  id: EnvCheckId
  title: string
  status: 'ok' | 'missing' | 'outdated'
  /** A blocking check that is not ok prevents opening a project. */
  blocking: boolean
  found?: string
  impact?: string
  hint?: string
  installUrl?: string
}

export interface EnvironmentReport {
  device: DeviceInfo
  checks: EnvCheck[]
  canOpenProject: boolean
}
