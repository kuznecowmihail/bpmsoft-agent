import { describe, it, expect, afterEach } from 'vitest'
import * as fs from 'fs'
import * as path from 'path'
import * as os from 'os'
import { validateBpmsoftProject } from '../src/main/projectValidation'

describe('validateBpmsoftProject', () => {
  let tmpRoot: string | undefined

  afterEach(() => {
    if (tmpRoot) {
      fs.rmSync(tmpRoot, { recursive: true, force: true })
      tmpRoot = undefined
    }
  })

  it('accepts a real BPMSoft.Configuration/Pkg folder and reports pkgRoot', () => {
    tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'bpmsoft-project-'))
    const pkgRoot = path.join(tmpRoot, 'BPMSoft.Configuration', 'Pkg')
    fs.mkdirSync(path.join(pkgRoot, 'MyPackage', 'Schemas'), { recursive: true })

    const result = validateBpmsoftProject(pkgRoot)

    expect(result.isValid).toBe(true)
    expect(result.kind).toBe('pkg')
    expect(result.pkgRoot).toBe(pkgRoot)
  })

  it('rejects an unrelated folder with a human-readable reason', () => {
    tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'not-bpmsoft-'))

    const result = validateBpmsoftProject(tmpRoot)

    expect(result.isValid).toBe(false)
    expect(result.kind).toBe('unknown')
    expect(result.reason).toContain('не похожа на BPMSoft-проект')
  })

  it('resolves sibling Resources/Autogenerated/conf when picking just the Pkg folder', () => {
    tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'bpmsoft-full-project-'))
    const appRoot = tmpRoot
    const configurationRoot = path.join(appRoot, 'BPMSoft.Configuration')
    const pkgRoot = path.join(configurationRoot, 'Pkg')
    fs.mkdirSync(path.join(pkgRoot, 'MyPackage', 'Schemas'), { recursive: true })
    fs.mkdirSync(path.join(configurationRoot, 'Autogenerated'), { recursive: true })
    fs.mkdirSync(path.join(appRoot, 'Resources'), { recursive: true })
    fs.mkdirSync(path.join(appRoot, 'conf', 'content'), { recursive: true })

    const result = validateBpmsoftProject(pkgRoot)

    expect(result.isValid).toBe(true)
    expect(result.appRoot).toBe(appRoot)
    expect(result.resourcesRoot).toBe(path.join(appRoot, 'Resources'))
    expect(result.autogeneratedRoot).toBe(path.join(configurationRoot, 'Autogenerated'))
    expect(result.confContent).toBe(path.join(appRoot, 'conf', 'content'))
  })
})
